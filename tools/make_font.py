#!/usr/bin/env python3
"""Generates btl_font.h: anti-aliased (4-bit) ASCII fonts for the bridge's screen.

Font: Inter by Rasmus Andersson (SIL Open Font License 1.1).
Usage: python3 tools/make_font.py /path/to/Inter-Medium.otf /path/to/Inter-SemiBold.otf /path/to/Inter-Bold.otf\n(also writes btl_wmfont.h, the 48 px print watermark font, from the SemiBold file)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = [("small", 0, 15), ("medium", 1, 20), ("large", 2, 34)]
FIRST, LAST = 32, 126

def build(path, px, name):
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    glyphs, bits = [], bytearray()
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        adv = int(round(f.getlength(ch)))
        box = f.getbbox(ch)                      # relative to the drawing origin (top of ascent)
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        off = len(bits)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
            px_ = list(im.getdata())
            for y in range(h):
                row = px_[y * w:(y + 1) * w]
                for x in range(0, w, 2):
                    a = row[x] >> 4
                    b = (row[x + 1] >> 4) if x + 1 < w else 0
                    bits.append((a << 4) | b)
        glyphs.append((off, w, h, box[0], box[1], adv))
    out = []
    out.append(f"static const uint8_t font_{name}_bits[] = {{")
    for i in range(0, len(bits), 24):
        out.append("  " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const BtlGlyph font_{name}_glyphs[] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"static const BtlFont font_{name} = {{ font_{name}_bits, font_{name}_glyphs, {asc + desc}, {asc} }};")
    return "\n".join(out), len(bits)

def write_wm(path):
    """The print watermark's font: one bigger size, its own header (only the watermark code includes it)."""
    txt, n = build(path, 48, "wm")
    parts = ["// Generated by tools/make_font.py - do not edit.",
             "// Font: Inter by Rasmus Andersson, SIL Open Font License 1.1 (https://rsms.me/inter/).",
             "#pragma once", "#include <stdint.h>", '#include "btl_font_types.h"', txt]
    open("btl-photo-bridge/btl_wmfont.h", "w").write("\n".join(parts) + "\n")
    print("watermark font bytes:", n)

def main():
    paths = sys.argv[1:4]
    parts = ["// Generated by tools/make_font.py - do not edit.",
             "// Font: Inter by Rasmus Andersson, SIL Open Font License 1.1 (https://rsms.me/inter/).",
             "#pragma once", "#include <stdint.h>", '#include "btl_font_types.h"']
    total = 0
    for name, i, px in SIZES:
        txt, n = build(paths[i], px, name)
        parts.append(txt); total += n
    open("btl-photo-bridge/btl_font.h", "w").write("\n".join(parts) + "\n")
    open("btl-photo-bridge/btl_font_types.h", "w").write("\n".join([
        "// Generated by tools/make_font.py - do not edit.", "#pragma once", "#include <stdint.h>",
        "struct BtlGlyph { uint32_t off; uint8_t w, h; int8_t x, y; uint8_t adv; };",
        "struct BtlFont { const uint8_t* bits; const BtlGlyph* glyphs; uint8_t lineH, ascent; };",
        f"#define BTL_FONT_FIRST {FIRST}", f"#define BTL_FONT_LAST {LAST}"]) + "\n")
    print("bitmap bytes:", total)
    write_wm(paths[1])

main()
